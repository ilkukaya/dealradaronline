/**
 * Provider-agnostic affiliate model.
 *
 * Every network adapter converts its own data into these normalized shapes.
 * Normalized offers are never published directly: the import script writes
 * them as `pending-verification` drafts that an editor reviews (see
 * docs/AFFILIATE_INTEGRATION.md).
 */
import type { NetworkId, PublisherAccountStatus } from './networks';
import type { CategorySlug, OfferTypeSlug } from '../../config/taxonomy';

export interface NormalizedMerchant {
  /** Our slug, e.g. "best-buy". */
  slug: string;
  name: string;
  domain: string;
  websiteUrl: string;
}

export interface NormalizedProgram {
  network: NetworkId;
  /** The network's advertiser/program identifier, exactly as the network reports it. */
  programId: string;
  merchant: NormalizedMerchant;
  status: PublisherAccountStatus;
  /** Commission terms as text from the network; never inferred. */
  commissionNote?: string;
}

export interface NormalizedCoupon {
  code: string;
  description?: string;
  minimumSpend?: number;
}

export interface NormalizedOffer {
  /** Stable ID from the source, used to de-duplicate imports. */
  sourceId: string;
  network: NetworkId;
  programId: string;
  merchant: NormalizedMerchant;
  title: string;
  description: string;
  category?: CategorySlug;
  offerType: OfferTypeSlug;
  currency: 'USD';
  price?: number;
  /** Only when the network supplies the merchant's own regular/compare price. */
  referencePrice?: number;
  coupon?: NormalizedCoupon;
  /** Plain landing page on the merchant site. */
  merchantUrl: string;
  /** Tracking link generated by the network for OUR publisher account. */
  affiliateUrl: string;
  startDate?: Date;
  endDate?: Date;
  /** When the network says this data was last updated. */
  sourceUpdatedAt?: Date;
  restrictions: string[];
  /** Raw tracking metadata kept for audits (never shown publicly). */
  tracking?: Record<string, string>;
}

export interface FetchOffersOptions {
  /** Only return offers for these network program IDs. */
  programIds?: string[];
  since?: Date;
  limit?: number;
}

export interface AffiliateAdapter {
  network: NetworkId;
  /** Environment variables required by this adapter. */
  requiredEnv: readonly string[];
  isConfigured(env: Record<string, string | undefined>): boolean;
  /** Programs this publisher account has joined. */
  listPrograms(env: Record<string, string | undefined>): Promise<NormalizedProgram[]>;
  /** Current offers/coupons from joined programs, normalized. */
  fetchOffers(env: Record<string, string | undefined>, options?: FetchOffersOptions): Promise<NormalizedOffer[]>;
}

export class AdapterNotConfiguredError extends Error {
  constructor(network: NetworkId, missing: string[]) {
    super(`${network}: missing environment variables ${missing.join(', ')}. See docs/AFFILIATE_INTEGRATION.md.`);
    this.name = 'AdapterNotConfiguredError';
  }
}

/**
 * Thrown where a network's API request/response mapping has not been written yet.
 * We deliberately don't guess at undocumented response formats: implement the
 * mapping against the network's current documentation once the account is approved.
 */
export class AdapterNotImplementedError extends Error {
  constructor(network: NetworkId, what: string, docsUrl: string) {
    super(`${network}: ${what} is not implemented yet. Implement it against the current API docs: ${docsUrl}`);
    this.name = 'AdapterNotImplementedError';
  }
}
